"""
precompute_trajectory_library.py

One-time precomputation step for the parametric bootstrap test.

For every candidate parameter set already generated by the LHS search
(parameter_samples_<NUM_SAMPLES>.csv), this script solves the ODE system
once under the single-sigmoid model and once under the double-sigmoid
model, and stores ONLY the 22 weekly cumulative-death predictions for
each -- not the full fine-grained (dt=0.01) trajectory.

X0/X1 ORDERING CONSTRAINT: candidates where the rise-midpoint (x0) isn't
meaningfully before the decline-onset (x1) are excluded from the DOUBLE
trajectory library only -- same constraint as
polish_vetlyanka_fit_double.py and build_frozen_library.py, and for the
same reason: without it, the bootstrap's "refit" step (searching this
library for whichever candidate best matches a synthetic dataset) could
pick a degenerate candidate where the two sigmoids overlap into a non-
physical shape that still happens to fit well, silently reintroducing
into the null distribution the exact problem the real point-estimate fit
now excludes. Does NOT apply to the single-sigmoid trajectory: x1 is
completely inert in that model, so a candidate failing this check is
still a perfectly valid, independent draw of the parameters single-
sigmoid actually uses.

WHY THIS STEP EXISTS, SEPARATELY FROM THE BOOTSTRAP ITSELF:
Simulating a candidate parameter set forward through the ODE does not
depend on which dataset (real or synthetic) you are eventually going to
score it against -- it only depends on the parameters themselves. So
instead of re-running ~num_samples ODE solves for every one of the
bootstrap replicates (millions of solve_ivp calls total), we solve every
candidate parameter set exactly once here, store the resulting weekly
trajectories, and in the bootstrap script we compare those stored
trajectories against many different synthetic datasets using ordinary
array arithmetic -- no further ODE solving required there.

This also means the bootstrap searches over the *same* finite set of
candidate parameter combinations that your real fit searched over,
which is what you want: the test should characterize the behaviour of
your actual fitting procedure (including whatever it can and can't
resolve), not a freshly-drawn, different LHS grid.

Run this once. It costs about as much compute as your original
single-model fit (same number of ODE solves, just done for both models
here), and only needs to be re-run if parameter_samples_<N>.csv, the
model definitions, or X0_X1_MIN_GAP change.

Expected inputs (same directory, or adjust paths below):
    parameter_samples_<NUM_SAMPLES>.csv  -- same file your fits used, see
                                             parameter_sampling.py
    plague_double_sigmoid_model.py
    plague_single_sigmoid_model.py

Outputs:
    double_trajectories.npy   (num_samples, 22)
    single_trajectories.npy   (num_samples, 22)
    candidate_params.npy      (num_samples, n_params)  -- for reference/debugging
"""

import numpy as np
from scipy.integrate import solve_ivp
import gc

# Import both model versions under distinct names.
from plague_double_sigmoid_model import plague_model as plague_model_double
from plague_single_sigmoid_model import plague_model as plague_model_single
from vetlyanka_bounds import PARAM_NAMES

import os
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SAMPLES_DIR = os.path.join(BASE_DIR, "data", "samples")
OUTPUT_DIR = os.path.join(BASE_DIR, "data", "bootstrap", "sigmoidal")
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ------------------------------------------------------------
# Settings -- must match your original fitting scripts exactly
# ------------------------------------------------------------
t_start, t_end, dt = 0, 22, 0.01
t_points = np.arange(t_start, t_end + dt, dt)
steps_per_week = int(round(1 / dt))
n_weeks = 22

initial_conditions = [1699, 1, 0, 0, 0, 0, 0]  # S, I, R, DI, DDI, DR, P

NUM_SAMPLES = 200000  # must match an existing parameter_samples_<NUM_SAMPLES>.csv
X0_X1_MIN_GAP = 1.0  # must match polish_vetlyanka_fit_double.py
T_PERCEIVE_FIXED_SIGMOID = 3.571  # must match polish_vetlyanka_fit_single_FIXED.py
IDX_T_PERCEIVE = PARAM_NAMES.index("T_perceive")
IDX_X0 = PARAM_NAMES.index("x0")
IDX_X1 = PARAM_NAMES.index("x1")

scaled_params_file = os.path.join(SAMPLES_DIR, f"parameter_samples_{NUM_SAMPLES}.csv")
sampleparam = np.loadtxt(scaled_params_file, delimiter=",", skiprows=1)
num_samples = sampleparam.shape[0]

# Optional: cap this while smoke-testing the pipeline end-to-end, then
# set back to None for the full run once you trust the output.
MAX_SAMPLES = None  # e.g. set to 2000 for a quick test run first
if MAX_SAMPLES is not None:
    sampleparam = sampleparam[:MAX_SAMPLES]
    num_samples = sampleparam.shape[0]

print(f"Precomputing weekly trajectories for {num_samples} candidate parameter sets...")
print(f"(double-sigmoid: excluding candidates with x1 - x0 < {X0_X1_MIN_GAP} weeks)")
print(f"(single-sigmoid: T_perceive forced to {T_PERCEIVE_FIXED_SIGMOID} for every candidate)")


def simulate_weekly(model_fn, params):
    """Solve the ODE for one parameter set; return 22 weekly cumulative DR
    values, or None if the solver failed or returned too few points."""
    sol = solve_ivp(
        model_fn, [t_start, t_end], initial_conditions,
        args=(params,), t_eval=t_points, method="RK45",
    )
    if not sol.success:
        return None
    DR = sol.y[5]
    weekly = DR[::steps_per_week][:n_weeks]
    if len(weekly) < n_weeks:
        return None
    return weekly


double_trajectories = np.full((num_samples, n_weeks), np.nan)
single_trajectories = np.full((num_samples, n_weeks), np.nan)
n_rejected_double = 0

for i, params in enumerate(sampleparam):
    if i % 1000 == 0 and i > 0:
        print(f"  sample {i}/{num_samples}  (double rejected so far: {n_rejected_double})")
        gc.collect()

    # Double: skip candidates where x0/x1 overlap into the degenerate
    # configuration -- see module docstring. Leaves double_trajectories[i]
    # as NaN, which the bootstrap script already filters out.
    if params[IDX_X0] < params[IDX_X1] - X0_X1_MIN_GAP:
        w_double = simulate_weekly(plague_model_double, params)
        if w_double is not None:
            double_trajectories[i, :] = w_double
    else:
        n_rejected_double += 1

    # Single: x1 is inert here, so this candidate is still a valid,
    # independent draw of the parameters single-sigmoid actually uses --
    # always compute it regardless of the double-only rejection above.
    # T_perceive is FIXED in the real single-sigmoid fit, not searched --
    # override it here too, so this library represents the actual model
    # being bootstrapped, not a more flexible one.
    params_single = params.copy()
    params_single[IDX_T_PERCEIVE] = T_PERCEIVE_FIXED_SIGMOID
    w_single = simulate_weekly(plague_model_single, params_single)
    if w_single is not None:
        single_trajectories[i, :] = w_single

np.save(os.path.join(OUTPUT_DIR, "double_trajectories.npy"), double_trajectories)
np.save(os.path.join(OUTPUT_DIR, "single_trajectories.npy"), single_trajectories)
np.save(os.path.join(OUTPUT_DIR, "candidate_params.npy"), sampleparam)

n_failed_double = int(np.isnan(double_trajectories).any(axis=1).sum())
n_failed_single = int(np.isnan(single_trajectories).any(axis=1).sum())
print("\nDone. Saved double_trajectories.npy and single_trajectories.npy.")
print(f"Double -- rejected for x0/x1 overlap: {n_rejected_double}, "
      f"total failed/excluded: {n_failed_double}")
print(f"Single -- failed solves: {n_failed_single}")